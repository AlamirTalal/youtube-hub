    let duration = liveDuration;
    if (ytPlayer && typeof ytPlayer.getCurrentTime === "function") {
      try {
        time = ytPlayer.getCurrentTime() || time;
        duration = ytPlayer.getDuration() || duration;
      } catch {}
    }
    savePosition(activeVideo.id, time, duration);
