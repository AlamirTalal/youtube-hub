function recordWatch(v) {
  watchStats.total = (watchStats.total || 0) + 1;

  const key =
    v._interest ||
    (currentView === "home" && mode === "search" && activeInterest ? activeInterest : null);
  if (key) watchStats.topics[key] = (watchStats.topics[key] || 0) + 1;

  if (v.channelId) {
    const channel = watchStats.channels[v.channelId] || { title: v.channelTitle, count: 0 };
    channel.title = v.channelTitle;
    channel.count = (channel.count || 0) + 1;
    watchStats.channels[v.channelId] = channel;
  }

  const day = localDay();
  watchStats.days[day] = (watchStats.days[day] || 0) + 1;
  watchStats.seconds = (watchStats.seconds || 0) + (Number(v.duration) || 0);

  store.set("watchStats", watchStats);
}

function barList(rows) {
  const wrap = document.createElement("div");
  wrap.className = "bar-list";
  rows.forEach(([name, count, ratio]) => {
    const row = document.createElement("div");
    row.className = "bar-row";

    const nameEl = document.createElement("span");
    nameEl.className = "bar-name";
    nameEl.textContent = name;

    const track = document.createElement("span");
    track.className = "bar-track";
    const fill = document.createElement("span");
    fill.className = "bar-fill";
    fill.style.width = `${Math.max(4, Math.round((ratio || 0) * 100))}%`;
    track.appendChild(fill);

    const countEl = document.createElement("span");
    countEl.className = "bar-count";
    countEl.textContent = String(count);

    row.append(nameEl, track, countEl);
    wrap.appendChild(row);
  });
  return wrap;
}

function weekChart() {
  const wrap = document.createElement("div");
  wrap.className = "week-chart";

  const days = [];
  for (let i = 6; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    days.push({ d, count: watchStats.days[localDay(d)] || 0 });
  }
  const max = Math.max(1, ...days.map((x) => x.count));

  days.forEach(({ d, count }) => {
    const col = document.createElement("div");
    col.className = "week-col";

    const value = document.createElement("span");
    value.className = "week-value";
    value.textContent = String(count);

    const bar = document.createElement("span");
    bar.className = "week-bar";
    bar.style.height = `${Math.round((count / max) * 100)}%`;

    const label = document.createElement("span");
    label.className = "week-label";
    label.textContent = new Intl.DateTimeFormat(lang, { weekday: "short" }).format(d);

    col.append(value, bar, label);
    wrap.appendChild(col);
  });

  return wrap;
}

function renderStatsView() {
  const grid = $("#results");
  if (!watchStats.total) {
    setStatus(t("statsEmpty"));
    return;
  }

  const summary = document.createElement("div");
  summary.className = "stats-summary";
  [
    [t("statWatched"), String(watchStats.total)],
    [t("statTime"), fmtDuration(watchStats.seconds || 0)],
    [t("statChannels"), String(Object.keys(watchStats.channels || {}).length)],
    [t("statTopics"), String(Object.keys(watchStats.topics || {}).length)],
  ].forEach(([name, value]) => {
    const box = document.createElement("div");
    box.className = "stat-box";
    const valueEl = document.createElement("span");
    valueEl.className = "stat-value";
    valueEl.textContent = value;
    const nameEl = document.createElement("span");
    nameEl.className = "stat-label";
    nameEl.textContent = name;
    box.append(valueEl, nameEl);
    summary.appendChild(box);
  });
  grid.appendChild(summary);

  const topics = Object.entries(watchStats.topics || {})
    .sort((a, b) => b[1] - a[1])
    .slice(0, 8);
  if (topics.length) {
    grid.appendChild(sectionTitle(t("statsTopics")));
    const max = topics[0][1] || 1;
    grid.appendChild(barList(topics.map(([key, count]) => [interestLabel(key), count, count / max])));
  }

  const channels = Object.entries(watchStats.channels || {})
    .map(([, channel]) => [channel.title, channel.count])
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5);
  if (channels.length) {
    grid.appendChild(sectionTitle(t("statsChannels")));
    const max = channels[0][1] || 1;
    grid.appendChild(barList(channels.map(([name, count]) => [name, count, count / max])));
  }

  grid.appendChild(sectionTitle(t("statsWeek")));
  grid.appendChild(weekChart());
}

