function currentOverlay() {
  const ids = ["playlistDialog", "settings", "player", "welcome"];
  for (const id of ids) {
    const el = document.getElementById(id);
    if (el && !el.classList.contains("hidden")) return el;
  }
  return null;
}

function showOverlay(el, focusSelector) {
  lastFocus = document.activeElement;
  el.classList.remove("hidden");
  const target = focusSelector ? el.querySelector(focusSelector) : null;
  if (target) target.focus({ preventScroll: true });
}

function hideOverlay(el) {
  el.classList.add("hidden");
  if (lastFocus && document.contains(lastFocus)) {
    lastFocus.focus({ preventScroll: true });
  }
  lastFocus = null;
}

const FOCUSABLE = 'a[href], button:not([disabled]), input:not([disabled]), select, textarea, [tabindex]:not([tabindex="-1"])';

function trapTab(e, overlay) {
  const items = [...overlay.querySelectorAll(FOCUSABLE)].filter(
    (el) => el.getClientRects().length > 0
  );
  if (!items.length) return;
  const first = items[0];
  const last = items[items.length - 1];
  if (e.shiftKey && document.activeElement === first) {
    e.preventDefault();
    last.focus();
  } else if (!e.shiftKey && document.activeElement === last) {
    e.preventDefault();
    first.focus();
  }
}

document.addEventListener("keydown", (e) => {
  const overlay = currentOverlay();
  if (overlay) {
    if (e.key === "Escape") {
      e.preventDefault();
      if (overlay.id === "player") closePlayer();
      else if (overlay.id === "settings") closeSettings();
      else if (overlay.id === "playlistDialog") closePlaylistDialog();
      else if (overlay.id === "welcome" && profile.onboarded) closeWelcome();
      return;
    }
    if (e.key === "Tab") trapTab(e, overlay);
    return;
  }
  if (e.key === "Escape" && document.body.classList.contains("sidebar-open")) {
    setSidebar(false);
  }
});

