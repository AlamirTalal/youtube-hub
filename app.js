async function loadFeed(force = false) {
  if (feedBusy && !force) return;
  const token = ++feedToken;
  feedBusy = true;
  setStatus(t("loading"));

  try {
    const all = allInterests();
    const valid = profile.interests.filter((k) => all.some((i) => i.key === k));
    const pool = valid.length ? valid : all.map((i) => i.key);
    const weights = pool.map((k) => 1 + (scores[k] || 0));
    const picks = weightedSample(pool, weights, Math.min(3, pool.length)).map((k) =>
      all.find((i) => i.key === k)
    );
    const order = randomItem(["relevance", "relevance", "date", "viewCount"]);

    const jobs = picks.map(async (interest) => {
      const code = pickLang();
      const data = await fetchVideos({
        q: randomItem(termsFor(interest, code)),
        lang: code,
        order,
      });
      return (data.items || []).map((v) => ({ ...v, _interest: interest.key }));
    });

    const results = (await Promise.all(jobs)).flat();
    if (token !== feedToken || mode !== "feed") return;

    const unique = shuffle(uniqById(results)).filter((v) => !isHidden(v));
    let fresh = unique.filter((v) => !seenSet.has(v.id));
    // لو خلص الجديد كله، اعرض تكرار بدل ما الفيد يبقى فاضي
    if (!fresh.length) fresh = unique;
    fresh.forEach((v) => seenSet.add(v.id));
    trimSeen();

    currentVideos = currentVideos.concat(fresh);
    if (currentView === "home") appendCards(fresh);
    setStatus(currentVideos.length ? "" : t("noResults"));
  } catch {
    if (token === feedToken) setStatus(t("error"));
  } finally {
    if (token === feedToken) feedBusy = false;
  }
}

