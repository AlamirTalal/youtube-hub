function deletePlaylist(id) {
  const index = playlists.findIndex((p) => p.id === id);
  if (index < 0) return;
  const [removed] = playlists.splice(index, 1);
  savePlaylists();
  if (currentPlaylistId === id) {
    currentPlaylistId = null;
    currentView = "playlists";
  }
  renderCurrentView();
  showToast(t("playlistDeleted"), t("undo"), () => {
    playlists.splice(Math.min(index, playlists.length), 0, removed);
    savePlaylists();
    renderCurrentView();
  });
}

function removeFromPlaylist(plId, v, card) {
  const pl = playlists.find((p) => p.id === plId);
  if (!pl) return;
  const snapshot = [...pl.videos];
  pl.videos = pl.videos.filter((x) => x.id !== v.id);
  savePlaylists();
  if (card) card.remove();
  if (!pl.videos.length) setStatus(t("emptyList"));
  showToast(t("removedFromList"), t("undo"), () => {
    pl.videos = snapshot;
    savePlaylists();
    refreshView();
  });
}

function renderPlaylistsView() {
  const grid = $("#results");

  const form = document.createElement("form");
  form.className = "playlist-create";
  const input = document.createElement("input");
  input.type = "text";
  input.maxLength = 50;
  input.placeholder = t("playlistName");
  input.setAttribute("aria-label", t("playlistName"));
  const addBtn = document.createElement("button");
  addBtn.type = "submit";
  addBtn.textContent = t("create");
  form.append(input, addBtn);
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const name = input.value.trim().replace(/\s+/g, " ").slice(0, 50);
    if (!name) return;
    playlists.unshift({ id: uid(), name, videos: [], createdAt: Date.now() });
    savePlaylists();
    renderCurrentView();
  });
  grid.appendChild(form);

  if (!playlists.length) {
    setStatus(t("playlistsEmpty"));
    return;
  }

  playlists.forEach((pl) => grid.appendChild(buildPlaylistRow(pl)));
}

function renderPlaylistDetail() {
  const grid = $("#results");
  const pl = playlists.find((p) => p.id === currentPlaylistId);
  if (!pl) {
    currentView = "playlists";
    renderCurrentView();
    return;
  }

  const head = document.createElement("div");
  head.className = "list-header";

  const back = document.createElement("button");
  back.type = "button";
  back.className = "pill-btn";
  back.textContent = t("back");
  back.onclick = () => switchView("playlists");

  const title = document.createElement("h2");
  title.className = "list-title";
  title.textContent = `${pl.name} — ${pl.videos.length} ${t("videos")}`;

  const del = document.createElement("button");
  del.type = "button";
  del.className = "pill-btn";
  del.textContent = t("deletePlaylist");
  del.onclick = () => deletePlaylist(pl.id);

  head.append(back, title, del);
  grid.appendChild(head);

  const list = filterVisible(pl.videos);
  if (!list.length) {
    setStatus(t("emptyList"));
    return;
  }

  appendCards(list, {
    action: {
      label: t("removeFromList"),
      icon: "playlist_remove",
      on: (v, card) => removeFromPlaylist(pl.id, v, card),
    },
  });
}

function renderCurrentView() {
  const grid = $("#results");
  grid.innerHTML = "";
  setStatus("");

  if (currentView === "home") {
    appendCards(filterVisible(currentVideos));
    return;
  }

  if (currentView === "likes") {
    const list = filterVisible(Object.values(likes));
    list.length ? appendCards(list) : setStatus(t("noItems"));
    return;
  }

  if (currentView === "history") {
    const list = filterVisible(history);
    list.length ? appendCards(list) : setStatus(t("noItems"));
    return;
  }

  if (currentView === "later") {
    const list = filterVisible(watchLater);
    if (!list.length) return setStatus(t("noItems"));
    appendCards(list, {
      action: {
        label: t("removeFromList"),
        icon: "playlist_remove",
        on: (v, card) => removeLater(v, card),
      },
    });
    return;
  }

  if (currentView === "playlists") {
    renderPlaylistsView();
    return;
  }

  if (currentView === "playlist") {
    renderPlaylistDetail();
    return;
  }

  if (currentView === "stats") {
    renderStatsView();
    return;
  }

  if (currentView === "follows") {
    const followed = Object.entries(follows);
    const blockedList = Object.entries(blocked);
    if (!followed.length && !blockedList.length) return setStatus(t("noItems"));

    if (followed.length) {
      grid.appendChild(sectionTitle(t("followedChannels")));
      followed.forEach(([id, ch]) => {
        grid.appendChild(
          channelRow(ch.title, ch.url, t("unfollow"), () => unfollowChannel(id))
        );
      });
    }

    if (blockedList.length) {
      grid.appendChild(sectionTitle(t("blockedChannels")));
      blockedList.forEach(([id, ch]) => {
        grid.appendChild(
          channelRow(ch.title, ch.url, t("unblock"), () => unblockChannel(id))
        );
      });
    }
  }
}

