function resumeFor(id) {
  const p = positions[id];
  if (!p || typeof p.t !== "number") return 0;
  if (p.d && p.t > p.d - 10) return 0;
  return p.t >= 10 ? Math.floor(p.t) : 0;
}

function savePosition(id, t, d) {
  if (!id || typeof t !== "number" || !Number.isFinite(t)) return;
  const sec = Math.floor(t);
  if (sec < 5 || (d && sec > d - 10)) {
    if (positions[id]) {
      delete positions[id];
      store.set("positions", positions);
    }
    return;
  }
  positions[id] = { t: sec, d: d ? Math.floor(d) : 0, at: Date.now() };
  const keys = Object.keys(positions);
  if (keys.length > 300) {
    keys.sort((a, b) => (positions[a].at || 0) - (positions[b].at || 0));
    keys.slice(0, keys.length - 300).forEach((k) => delete positions[k]);
  }
  store.set("positions", positions);
}

function clearPosition(id) {
  if (positions[id]) {
    delete positions[id];
    store.set("positions", positions);
  }
}

function embedUrl(v, start) {
  const url = new URL(`https://www.youtube.com/embed/${encodeURIComponent(v.id)}`);
  url.searchParams.set("rel", "0");
  url.searchParams.set("playsinline", "1");
  if (start > 0) url.searchParams.set("start", String(Math.floor(start)));
  return url.toString();
}

function ensureYT() {
  if (window.YT && window.YT.Player) return Promise.resolve(window.YT);
  if (ytPromise) return ytPromise;
  ytPromise = new Promise((resolve, reject) => {
    const prev = window.onYouTubeIframeAPIReady;
    window.onYouTubeIframeAPIReady = () => {
      if (typeof prev === "function") prev();
      resolve(window.YT);
    };
    const script = document.createElement("script");
    script.src = "https://www.youtube.com/iframe_api";
    script.async = true;
    script.onerror = () => reject(new Error("YouTube API failed"));
    document.head.appendChild(script);
  });
  ytPromise.catch(() => { ytPromise = null; });
  return ytPromise;
}

function mountVideo(v, start) {
  const token = ++ytToken;
  const wrap = $("#videoFrameWrap");
  wrap.innerHTML = '<div id="videoFrame" class="video-frame"></div>';
  const host = $("#videoFrame");
  host.title = v.title;
  ytPlayer = null;
  ytReady = false;
  fallbackFrame = null;

  const fallback = () => {
    if (token !== ytToken || fallbackFrame) return;
    if (ytPlayer && typeof ytPlayer.destroy === "function") {
      try { ytPlayer.destroy(); } catch {}
    }
    ytPlayer = null;
    const container = $("#videoFrameWrap");
    if (!container) return;
    container.innerHTML = "";
    const iframe = document.createElement("iframe");
    iframe.id = "videoFrame";
    iframe.className = "video-frame";
    iframe.title = v.title;
    iframe.allow = "accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture";
    iframe.allowFullscreen = true;
    iframe.referrerPolicy = "strict-origin-when-cross-origin";
    iframe.src = embedUrl(v, start);
    container.appendChild(iframe);
    fallbackFrame = iframe;
  };

  ensureYT()
    .then((YT) => {
      if (token !== ytToken || fallbackFrame) return;
      ytPlayer = new YT.Player(host, {
        width: "100%",
        height: "100%",
        videoId: v.id,
        playerVars: {
          rel: 0,
          playsinline: 1,
          start: start || 0,
          origin: location.origin,
        },
        events: {
          onReady: (e) => {
            if (token !== ytToken || fallbackFrame) return;
            ytReady = true;
            const frame = e.target.getIframe ? e.target.getIframe() : null;
            if (frame) frame.title = v.title;
            startTrack();
          },
          onStateChange: (e) => {
            if (token !== ytToken) return;
            if (e.data === 0) clearPosition(v.id);
          },
        },
      });
    })
    .catch(fallback);

  // لو الـ API اتأخر/اتمنع، استخدم iframe مباشر عشان المشغل يفضل شغال
  window.setTimeout(() => {
    if (token === ytToken && !ytReady && !fallbackFrame) fallback();
  }, 6000);
}

function startTrack() {
  stopTrack();
  trackTimer = setInterval(() => {
    if (!activeVideo || !ytPlayer || typeof ytPlayer.getCurrentTime !== "function") return;
    let time = 0;
    let duration = 0;
    try {
      time = ytPlayer.getCurrentTime() || 0;
      duration = ytPlayer.getDuration() || 0;
    } catch {
      return;
    }
    if (!time) return;
    liveTime = time;
    liveDuration = duration;
    savePosition(activeVideo.id, time, duration);
  }, 5000);
}

function stopTrack() {
  if (trackTimer) {
    clearInterval(trackTimer);
    trackTimer = null;
  }
}

